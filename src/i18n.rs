//! UI strings. A struct per language, so a missing translation is a compile error.
use crate::store::Lang;
use dioxus::prelude::*;

pub static LANG: GlobalSignal<Lang> = Signal::global(|| Lang::En);

/// Strings for the current language. Reading it subscribes the component to language changes.
pub fn tr() -> &'static Tr {
    match LANG() {
        Lang::En => &EN,
        Lang::Ja => &JA,
    }
}

pub fn kind_label(kind: crate::store::Kind) -> &'static str {
    let t = tr();
    match kind {
        crate::store::Kind::Productive => t.productive,
        crate::store::Kind::Wasted => t.wasted,
        crate::store::Kind::Break => t.break_time,
    }
}

/// Replaces `{name}` placeholders.
pub fn fill(template: &str, args: &[(&str, &str)]) -> String {
    args.iter().fold(template.to_string(), |s, (k, v)| s.replace(&format!("{{{k}}}"), v))
}

