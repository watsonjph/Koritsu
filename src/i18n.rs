#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_replaces_every_placeholder() {
        assert_eq!(fill(EN.nudge, &[("d", "3h 0m"), ("p", "today"), ("n", "40")]), "You wasted 3h 0m today! 40% of your tracked time was productive.");
        assert!(!fill(JA.nudge, &[("d", "1"), ("p", "2"), ("n", "3")]).contains('{'));
    }
}
